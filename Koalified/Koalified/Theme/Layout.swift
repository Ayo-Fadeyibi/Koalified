    static let radiusLarge: CGFloat = 20    // widgets and big panels

    // Spacing
    static let screenPadding: CGFloat = 16
    static let sectionSpacing: CGFloat = 12

    // Floating add button
    static let fabSize: CGFloat = 56
    static let fabPadding: CGFloat = 20
}
